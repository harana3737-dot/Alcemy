def strip_guide(text):
    """Возвращает исходное тело побайтно (UTF-8), включая пробелы и переносы."""
    return BLOCK.sub('', text)


def guide_block(name, text):
    conclusions, route = GUIDES[name]
    # Число каталога берётся из самого собранного документа, а не из старой ветки.
    if name == 'Карточки эликсиров':
        count = re.search(r'Всего карточек: (\d+)\.', text)
        if not count:
            raise ValueError('В каталоге отсутствует число карточек')
        conclusions = (f'Из {count[1]} карточек для варки подходят уровни в пределах мастерства алхимика; известные рецепты проверяются отдельно.',) + conclusions[1:]
    if name == 'Реестр расхождений с источниками':
        counts = re.search(r'Проверено карточек: (\d+) из (\d+);.*?С отличиями: (\d+)\. Не объяснено: (\d+)\.', text)
        if not counts:
            raise ValueError('В реестре отсутствуют итоги сверки')
        checked, total, changed, unexplained = counts.groups()
        conclusions = (f'Сверено {checked} из {total} карточек; с отличиями — {changed}, без объяснения — {unexplained}.',) + conclusions[1:]
    lines = [START]
    if name in BUILD_SOURCES:
        builder, source = BUILD_SOURCES[name]
        lines.append(marker(builder, source, partial=name in PARTIAL))
    if conclusions:
        lines += ['## Коротко', ''] + ['- ' + item for item in conclusions] + ['']
    lines += ['**Как читать.** ' + route, END, '', '']
    return '\n'.join(lines)


def add_guide(text, name):
    """Вставляет блок после вступления; повторный вызов заменяет только свой блок."""
    body = strip_guide(text)
    title_end = body.find('\n\n')
    intro_end = body.find('\n\n', title_end + 2)
    at = intro_end + 2 if intro_end >= 0 else title_end + 2
    if title_end < 0:
        raise ValueError('Ожидались заголовок и пустая строка')
    # Когда сразу за заголовком начинается раздел/таблица, вступления нет.
    if body[title_end + 2:].startswith(('## ', '| ', '<a ')):
        at = title_end + 2
    return body[:at] + guide_block(name, body) + body[at:]


def guide_html(text, name):
    """Небольшой HTML-блок для каталога с собственным сборщиком HTML."""
    import html
    conclusions, route = GUIDES[name]
    block = guide_block(name, strip_guide(text))
    items = re.findall(r"^- (.+)$", block, re.M)
    return ('<section class="reading-guide"><h2>Коротко</h2><ul>'
            + ''.join('<li>' + html.escape(item) + '</li>' for item in items)
            + '</ul><p><b>Как читать.</b> ' + html.escape(route) + '</p></section>')
