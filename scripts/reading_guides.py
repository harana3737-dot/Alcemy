def guide(filename):
    status, points, route = READING_GUIDES[filename]
    return ('**' + status + '**\n\n' +
            'Коротко:\n\n' + '\n'.join('- ' + point for point in points) +
            '\n\n**Как читать.** ' + route + '\n\n')


def add_reading_guide(text, filename):
    """Вставить маршрут после заголовка один раз; остальной текст неизменен."""
    text = normalize_prose(text)
    block = guide(filename)
    if block in text:
        return text
    title, separator, body = text.partition('\n')
    if not separator or not title.startswith('# '):
        raise ValueError('Ожидался заголовок документа: ' + filename)
    return title + '\n\n' + block + body.lstrip('\n')


def normalize_prose(text):
    """Русские обозначения и короткие абзацы; код и пути остаются исходными."""
    import re

    terms = {'STR': 'Сила', 'DEX': 'Ловкость', 'CON': 'Телосложение',
             'INT': 'Интеллект', 'WIS': 'Мудрость', 'CHA': 'Харизма',
             'LR': 'легендарное сопротивление', 'CR': 'опасность',
             'AC': 'КД', 'DC': 'СЛ', 'HP': 'хиты'}

    def translate(part):
        part = re.sub(r'(?<![A-Za-z_])d(\d+)\b', r'к\1', part)
        part = re.sub(r'\bL(\d+)\b', r'ур. \1', part)
        part = re.sub(r'\bM(\d+)\b', r'мастерство \1', part)
        part = re.sub(r'\b(?:' + '|'.join(terms) + r')\b',
                      lambda match: terms[match[0].upper()], part, flags=re.I)
        for old, new in (
                ('при мастерство', 'при мастерстве'),
                ('на мастерство', 'на мастерстве'),
                ('с мастерство', 'с мастерства'),
                ('до мастерство', 'до мастерства'),
                ('для мастерство', 'для мастерства'),
                ('перед мастерство', 'перед мастерством'),
                ('после мастерство', 'после мастерства'),
                ('После мастерство', 'После мастерства'),
                ('оставшемся мастерство', 'оставшемся мастерстве'),
                ('выше M', 'выше своего мастерства'),
                ('рост M', 'рост мастерства'),
                ('Рост M', 'Рост мастерства'),
                ('высокое M', 'высокое мастерство'),
                ('Высокое M', 'Высокое мастерство'),
                ('высоком M', 'высоком мастерстве'),
                ('высокого M', 'высокого мастерства'),
                ('по M и L', 'по мастерству и уровню персонажа'),
                ('по L', 'по уровню персонажа'),
                ('разном M', 'разном мастерстве'),
                ('следующего M', 'следующей ступени мастерства'),
                ('Новое M', 'Новое мастерство'),
                ('новое M', 'новое мастерство'),
                ('повышение M', 'повышение мастерства'),
                ('повышение L', 'повышение уровня персонажа'),
                ('Повышение M', 'Повышение мастерства'),
                ('Повышение L', 'Повышение уровня персонажа'),
                ('Уровень персонажа L', 'Уровень персонажа'),
                ('Мастерство алхимии M', 'Мастерство алхимии'),
                ('| M /', '| Мастерство /'),
                ('M — требуемое мастерство, не уровень персонажа.',
                 'Требуемое мастерство алхимии указано отдельно от уровня персонажа.'),
                ('высокое мастерство/рецепты', 'высокое мастерство и освоенные рецепты')):
            part = re.sub(re.escape(old) + r'(?![А-Яа-яЁёA-Za-z])',
                          lambda match: new, part)
        genitive = {'Сила': 'Силы', 'Ловкость': 'Ловкости',
                    'Телосложение': 'Телосложения', 'Интеллект': 'Интеллекта',
                    'Мудрость': 'Мудрости', 'Харизма': 'Харизмы'}
        part = re.sub(r'(спасброс(?:ок|ки|ка|ков) )(' + '|'.join(genitive) + r')\b',
                      lambda match: match[1] + genitive[match[2]], part)
        return part

    lines, fenced = [], False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith(('```', '~~~')):
            fenced = not fenced
        if fenced or line.startswith('    ') or line.lstrip().startswith(('```', '~~~', '<')):
            lines.append(line)
            continue
        # Не переводить идентификаторы и названия внутри inline-кода,
        # адреса ссылок, явные якоря и HTML-теги.
        chunks = re.split(r'(`[^`]*`|https?://\S+|\]\([^)]*\)|<[^>]*>)', line)
        line = ''.join(part if i % 2 else translate(part)
                       for i, part in enumerate(chunks))
        if (len(line) > 500 and
                not line.lstrip().startswith(('#', '|', '-', '* ', '>', '<')) and
                not re.match(r'\s*\d+\. ', line)):
            sentences = re.split(r'(?<=[.!?]) (?=[А-ЯЁ«])', line.rstrip('\n'))
            paragraphs, current = [], ''
            for sentence in sentences:
                if current and len(current) + len(sentence) > 350:
                    paragraphs.append(current)
                    current = sentence
                else:
                    current = (current + ' ' + sentence).lstrip()
            if current:
                paragraphs.append(current)
            line = '\n\n'.join(paragraphs) + ('\n' if line.endswith('\n') else '')
        lines.append(line)
    return ''.join(lines)
