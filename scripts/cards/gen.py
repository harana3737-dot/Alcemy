def add_en(s):
    def rep(m):
        ru = m.group(1)
        return f"«{ru}» ({EN[ru]})" if ru in EN else m.group(0)
    s = re.sub(r"«([^»]+)»", rep, s)
    s = re.sub(r"(«[^»]+» \([A-Za-z'/ ]+\)) \([^)]*\)", r"\1", s)  # только названия
    s = re.sub(r"заклинани[ея] ", "", s)
    return re.sub(r" \(\d ур\.\)$", "", s)


