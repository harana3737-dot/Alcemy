def src_range(c):
    m = re.search(r"\d ур\.; ([^)]*)\)", c["src_raw"])
    if not m:
        return None
    parts = [p.strip() for p in m.group(1).split(",")]
    parts = [p for p in parts if not any(w in p for w in DUR_WORDS) or "фт" in p]
    return ", ".join(parts) or None


