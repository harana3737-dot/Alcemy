import re
SEC = r"(?:\d+\.\d+|А\.\d)"
FIX = [
    ("СЛ 13 — по 3.5 и таблице 8.8.", "СЛ 13 — по 3.5 и таблице СЛ зарядов."),
    ("табличная СЛ 8.8 (13)", "табличная СЛ 13"),
    ("ориентир — 8.8 (заклинательный, иначе табличный +5)", "ориентир — заклинательный, иначе табличный +5"),
    ("СЛ спасброска — по 8.8 (табличная 15)", "СЛ спасброска — табличная 15"),
    ("По 8.7 дополнительное", "Дополнительное"), ("но по 8.7 прибавка", "но прибавка"),
    ("по 9.1 v0.3", "по v0.3"), ("канон 8.5", "канон v0.2"), ("DMG 3.5", "D&D 3.5"), ("по 3.5 и", "по D&D 3.5 и"),
    ("(правило сильных масел, 8.11)", "(правило сильных масел)"),
]
def clean(s):
    for a, b in FIX:
        s = s.replace(a, b)
    s = re.sub(rf"\(([^()]*?), {SEC}\)", r"(\1)", s)      # (мягкий, 8.7) → (мягкий)
    s = re.sub(rf"\(([^()]*?), {SEC}; ", r"(\1; ", s)      # (мягкий, 8.7; …
    s = re.sub(rf" \({SEC}(?:, {SEC})*\)", "", s)          # « (8.8)», « (А.6)»
    return s
