def hit_probability(attack, ac):
    return sum(d == 20 or d != 1 and d + attack >= ac for d in range(1,21))/20


def proficiency(level):
    return 2+(level-1)//4


def toxicity_limit(level, constitution_modifier):
    """Бонус мастерства персонажа; не уровень/бонус мастерства алхимии."""
    return 2+constitution_modifier+proficiency(level)


def incoming(ac, dex, attacks=8, enemy_attack=6, mirror=False, disadvantage=False):
    """Точная цепь числа живых образов; фиксированный урон10 за попадание.

    Криты не удваивают модельный урон. Нет реакций/АОЕ/особого зрения.
    Сочетание Размытия и Образов не оценивается.
    """
    p = hit_probability(enemy_attack,ac)
    if disadvantage:
        p *= p
    image_hit = hit_probability(enemy_attack,10+dex)
    states = {3 if mirror else 0:1.0}
    total = 0
    for _ in range(attacks):
        nxt = {}
        for count, weight in states.items():
            redirect = {0:0,1:.5,2:.65,3:.75}[count]
            total += weight * (1-redirect) * p * 10
            destroyed = redirect * image_hit
            nxt[count] = nxt.get(count,0)+weight*(1-destroyed)
            if count:
                nxt[count-1] = nxt.get(count-1,0)+weight*destroyed
        states = nxt
    return total


def weapon_damage(level, tenser=False, haste=False, strength=18, ac=18):
    """Двуручный меч2d6; без бонуса магического оружия/стиля/расходуемых кар."""
    pb=proficiency(level)
    mod=(strength-10)//2
    p=hit_probability(pb+mod,ac)
    crit=.05
    if tenser:
        p=1-(1-p)**2
        crit=1-.95**2
    dice=7+(4.5 if level>=11 else 0)+(13 if tenser else 0)
    attacks=(2 if level>=5 or tenser else 1)+int(haste)
    return attacks*(p*(dice+mod)+crit*dice)


