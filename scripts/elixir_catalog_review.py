@lru_cache(None)
def brewing_profile(level, bonus, first=False, runs=3000):
    dc = ELIXIR_DC[level]+2*first
    def stable(b):
        return sum(d==20 or d!=1 and d+b>=dc for d in range(1,21))/20
    if level<=5:
        p=stable(bonus); hours=2 if level<=2 else 4
        return dict(success=p, attempt_hours=hours, stable_hours=hours/p, method='exact')
    rng=random.Random(20261115+level*1000+bonus*10+int(first))
    steps=prob=0
    for _ in range(runs):
        progress=marks=hitches=defects=0
        while progress<WORK_VOLUME[level]:
            steps+=1; d=rng.randint(1,20); total=d+bonus
            if d==20:
                progress+=2*total; marks+=1
            elif d==1:
                progress=max(0,progress-rng.randint(1,20)); defects+=1
            elif total>=dc:
                progress+=total; marks+=2 if total>=dc+10 else int(total>=dc+5)
            elif total>=dc-4:
                progress+=total/2; hitches+=1
                if hitches==3:
                    hitches=0; defects+=1
            else:
                defects+=1
        prob+=stable(bonus+max(-2,min(2,marks-defects)))
    p=prob/runs; hours=2*steps/runs
    return dict(success=p, attempt_hours=hours, stable_hours=hours/p,
                method='seeded simulation; final die exact', runs=runs)


