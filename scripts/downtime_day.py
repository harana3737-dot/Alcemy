def ink_day(bonus, remaining, attempts=5):
    # Состояние: набранный прогресс, стоимость трав, потраченные указания.
    active = {(0, 0, 0): 1.0}
    terminal = []
    finished = defaultdict(float)
    for count in range(1, attempts + 1):
        following = defaultdict(float)
        for (progress, cost, points), probability in active.items():
            for first in range(1, 21):
                for face in (range(1, 21) if first == 1 else (first,)):
                    mass = probability / (400 if first == 1 else 20)
                    total = progress + face + bonus
                    expense = cost + (0 if face == 20 else 60 if face == 1 else 30)
                    used = points + (first == 1)
                    done = total >= remaining
                    if done or count == attempts:
                        terminal.append((count, expense, used, done, mass))
                        if done:
                            finished[count] += mass
                    else:
                        following[total, expense, used] += mass
        active = following
    costs = defaultdict(float)
    for _, cost, _, _, mass in terminal:
        costs[cost] += mass
    assert abs(sum(costs.values()) - 1) < 1e-10
    return dict(
        by_attempt=dict(finished), completion=sum(finished.values()),
        cost=sum(c * p for c, p in costs.items()),
        hours=sum(2 * n * p for n, _, _, _, p in terminal),
        points=sum(u * p for _, _, u, _, p in terminal), costs=dict(costs),
    )


def final_rolls(bonus, dc):
    for first in range(1, 21):
        failed = first == 1 or (first != 20 and first + bonus < dc)
        for face in (range(1, 21) if failed else (first,)):
            yield face, 1 / (400 if failed else 20)


