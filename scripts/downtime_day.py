def verify(runs=100000):
    rng = random.Random(20261101)
    for bonus in (5, 7):
        exact = ink_day(bonus, 70)
        costs, times, completions = [], [], []
        for _ in range(runs):
            progress = cost = 0
            for count in range(1, 6):
                face = rng.randint(1, 20)
                if face == 1:
                    face = rng.randint(1, 20)
                progress += face + bonus
                cost += 0 if face == 20 else 60 if face == 1 else 30
                if progress >= 70:
                    break
            costs.append(cost)
            times.append(2 * count)
            completions.append(progress >= 70)
        for name, values, target in (
            ('стоимость', costs, exact['cost']),
            ('время', times, exact['hours']),
            ('завершение', completions, exact['completion']),
        ):
            mean = sum(values) / runs
            variance = sum((v - mean) ** 2 for v in values) / (runs - 1)
            se = sqrt(variance / runs)
            if abs(mean - target) > 5 * se + 1e-9:
                raise AssertionError((bonus, name, mean, target, se))
        print(f'PASS: +{bonus}, {runs} независимых дней; вероятность, время и стоимость в пределах 5 стандартных ошибок')


